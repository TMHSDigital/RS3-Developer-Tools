// Assemble a LuaLS addon from the generated stubs, for editors that do not use
// npm: the LuaLS addon manager (LLS-Addons) and anyone who wants a folder they
// can point workspace.library at.
//
//   node scripts/build-luals-addon.mjs [--out <dir>] [--stubs <packages/luals-stubs>]
//
// Layout, following the LLS-Addons convention (one addon per repository):
//   <out>/config.json   settings the addon applies (Lua 5.4, no third-party prompts)
//   <out>/info.json     name, description, size, hasPlugin
//   <out>/library/      the ---@meta stubs
//   <out>/README.md     what it is and where it comes from
// The release workflow zips this folder beside the npm tarballs.

import { promises as fsp, realpathSync } from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

async function copyTree(from, to) {
  await fsp.mkdir(to, { recursive: true });
  for (const entry of await fsp.readdir(from, { withFileTypes: true })) {
    const src = path.join(from, entry.name);
    const dest = path.join(to, entry.name);
    if (entry.isDirectory()) await copyTree(src, dest);
    else await fsp.copyFile(src, dest);
  }
}

async function treeSize(dir) {
  let total = 0;
  for (const entry of await fsp.readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    total += entry.isDirectory() ? await treeSize(full) : (await fsp.stat(full)).size;
  }
  return total;
}

/** Build the addon folder. Returns a summary. */
export async function buildLualsAddon({ out, stubsPackage = path.join(repoRoot, "packages", "luals-stubs") } = {}) {
  const outDir = path.resolve(out ?? path.join(repoRoot, "dist", "luals-addon"));
  const pkg = JSON.parse(await fsp.readFile(path.join(stubsPackage, "package.json"), "utf8"));
  const index = JSON.parse(await fsp.readFile(path.join(stubsPackage, "index.json"), "utf8"));
  await fsp.rm(outDir, { recursive: true, force: true });
  await copyTree(path.join(stubsPackage, "stubs"), path.join(outDir, "library"));
  const size = await treeSize(path.join(outDir, "library"));
  const config = {
    settings: {
      "Lua.runtime.version": "Lua 5.4",
      "Lua.workspace.checkThirdParty": false,
      "Lua.diagnostics.globals": [],
    },
  };
  const info = {
    name: "RuneScape Client API",
    description: `Type stubs for the official RuneScape 3 plugin API (RuneScape Client API): ${index.modules.length} documentation pages, ${index.symbols.length} symbols, signatures and docs links only. Generated by RS3 Developer Tools ${pkg.version}.`,
    size,
    hasPlugin: false,
  };
  await fsp.writeFile(path.join(outDir, "config.json"), JSON.stringify(config, null, 2) + "\n");
  await fsp.writeFile(path.join(outDir, "info.json"), JSON.stringify(info, null, 2) + "\n");
  await fsp.writeFile(
    path.join(outDir, "README.md"),
    [
      "# RuneScape Client API (LuaLS addon)",
      "",
      `Type stubs for the official RuneScape 3 plugin API, generated from https://developer.runescape.com/rs/ by RS3 Developer Tools ${pkg.version}: ${index.modules.length} pages, ${index.symbols.length} symbols. The files carry signatures and \`@see\` links only; the documentation itself is copyright Jagex and stays on the site.`,
      "",
      "## Use",
      "",
      '- LuaLS addon manager (VS Code): enable "RuneScape Client API" and open your plugin folder.',
      "- Any editor: add `library/` to `workspace.library` in `.luarc.json` and set `runtime.version` to `Lua 5.4` (see `config.json`).",
      "",
      "Source, CLI, MCP server and the weekly regeneration: https://github.com/TMHSDigital/RS3-Developer-Tools",
      "",
    ].join("\n"),
  );
  return { outDir, files: (await fsp.readdir(path.join(outDir, "library"))).length, size, version: pkg.version };
}

async function main(argv) {
  const value = (flag) => {
    const i = argv.indexOf(flag);
    return i >= 0 ? argv[i + 1] : undefined;
  };
  const result = await buildLualsAddon({ out: value("--out"), stubsPackage: value("--stubs") });
  console.log(`built LuaLS addon ${result.version} in ${result.outDir} (${result.files} top-level library entries, ${(result.size / 1024).toFixed(0)} KB)`);
}

const invoked = process.argv[1] ? realpathSync(process.argv[1]) : "";
if (invoked === realpathSync(fileURLToPath(import.meta.url))) await main(process.argv.slice(2));
