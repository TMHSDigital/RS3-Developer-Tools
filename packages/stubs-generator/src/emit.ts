// Renders the resolved API model as LuaLS ---@meta files.
//
// Output rules:
//   - signatures only: names, parameter and return types, fields, enum members,
//     plus a @see link to the exact docs anchor. No descriptions.
//   - one file per documentation page, mirroring the docs path
//   - deterministic: members keep document order, derived sets are sorted,
//     no timestamps

import type {
  ClassDef,
  EnumDef,
  EventDef,
  FunctionSig,
  GlobalTables,
  HookDef,
  IndexEntry,
  ModuleDef,
  Param,
} from "./types.js";
import { renderFunParams, renderFunType } from "./lua-types.js";

export interface EmitOptions {
  baseUrl: string;
  /** Class names referenced anywhere but never declared; emitted as "any" aliases. */
  unresolved: { name: string; references: string[] }[];
  /** Explicit aliases from overrides. */
  aliases: { name: string; type: string; see: string }[];
  globalFunctions: { name: string; params: Param[]; see: string }[];
  globals: GlobalTables;
  namespaces: string[];
}

export interface EmittedFile {
  path: string;
  content: string;
}

const HEADER_NOTE = [
  "-- Generated by @tmhs/rs3-stubs-generator from the RuneScape Client API docs.",
  "-- Signatures only (names, types, fields, enum members). Descriptions stay on the docs site.",
  "-- Do not edit by hand; regenerate with: npm run stubs:generate",
];

function header(title: string, url: string): string[] {
  return ["---@meta", `-- RuneScape Client API stubs: ${title}`, ...HEADER_NOTE, `-- Docs: ${url}`, ""];
}

function see(url: string, anchor: string): string {
  return `---@see ${url}${anchor ? "#" + anchor : ""}`;
}

/** Name of the Lua variable a class's methods are attached to. */
function tableName(cls: ClassDef): string {
  if (cls.isGlobal) return cls.name;
  return cls.name.replace(/\./g, "_") + "_";
}

function paramLines(params: Param[]): string[] {
  return params.map((p) =>
    p.vararg ? `---@param ... ${p.type}` : `---@param ${p.name}${p.optional ? "?" : ""} ${p.type}`,
  );
}

function paramNames(params: Param[]): string {
  return params.map((p) => (p.vararg ? "..." : p.name)).join(", ");
}

function functionBlock(sig: FunctionSig, owner: string, url: string): string[] {
  // The docs link goes first: LuaLS keeps binding the block to the statement that follows.
  const lines: string[] = [see(url, sig.anchor)];
  lines.push(...paramLines(sig.params));
  for (const ret of sig.returns) lines.push(`---@return ${ret}`);
  for (const overload of sig.overloads) {
    lines.push(`---@overload ${renderFunType(overload.params, overload.returns)}`);
  }
  const qualified = owner ? `${owner}${sig.sep}${sig.name}` : sig.name;
  lines.push(`function ${qualified}(${paramNames(sig.params)}) end`, "");
  return lines;
}

export function signatureText(sig: FunctionSig): string {
  const owner = sig.owner ? `${sig.owner}${sig.sep}` : "";
  const ret = sig.returns.length > 0 ? `: ${sig.returns.join(", ")}` : "";
  return `function ${owner}${sig.name}(${renderFunParams(sig.params)})${ret}`;
}

function enumBlock(e: EnumDef, url: string): string[] {
  const lines: string[] = [];
  const valued = e.members.length > 0 && e.members.every((m) => m.value !== undefined);
  if (valued) {
    lines.push(see(url, e.anchor), `---@enum ${e.name}`, `${e.name} = {`);
    for (const m of e.members) lines.push(`    ${m.name} = ${m.value},`);
    lines.push("}", "");
  } else {
    lines.push(see(url, e.anchor), `---@class ${e.name}`);
    for (const m of e.members) lines.push(`---@field ${m.name} ${e.name}`);
    lines.push(`${e.name} = {}`, "");
  }
  return lines;
}

function classBlock(cls: ClassDef, url: string): string[] {
  const lines: string[] = [see(url, cls.anchor)];
  lines.push(`---@class ${cls.name}${cls.parent ? " : " + cls.parent : ""}`);
  for (const f of cls.fields) lines.push(`---@field ${f.name} ${f.type}`);
  if (cls.index) lines.push(`---@field [${cls.index.keyType}] ${cls.index.valueType}`);
  const name = tableName(cls);
  lines.push(cls.isGlobal ? `${name} = {}` : `local ${name} = {}`, "");
  for (const m of cls.methods) lines.push(...functionBlock(m, name, url));
  return lines;
}

function eventBlock(ev: EventDef, url: string): string[] {
  const lines: string[] = [];
  const payloadClass = `${ev.name}Event`;
  if (ev.payload.length > 0) {
    lines.push(see(url, ev.anchor), `---@class ${payloadClass}`);
    for (const f of ev.payload) lines.push(`---@field ${f.name} ${f.type}`);
    lines.push("");
  }
  const callback = ev.payload.length > 0 ? `fun(e: ${payloadClass})` : "fun()";
  const ret = ev.returnsBoolean ? ": boolean" : "";
  lines.push(see(url, ev.anchor), `---@class Event.${ev.name}`, `Event.${ev.name} = {}`, "");
  lines.push(
    see(url, ev.anchor),
    "---@param ref string",
    `---@param callback ${callback}${ret}`,
    `function Event.${ev.name}.Subscribe(ref, callback) end`,
    "",
    see(url, ev.anchor),
    "---@param ref string",
    `function Event.${ev.name}.Unsubscribe(ref) end`,
    "",
  );
  return lines;
}

function hookBlocks(hooks: HookDef[], url: string): string[] {
  if (hooks.length === 0) return [];
  const lines: string[] = [];
  for (const hook of hooks) {
    const variants = hook.variants.map((v) => renderFunType(v, ["boolean?"]));
    lines.push(`---@alias ui.HookCallback.${hook.name} ${variants.join("|")}`);
  }
  lines.push("", see(url, hooks[0]!.anchor), "---@class ui.Hook");
  for (const hook of hooks) lines.push(`---@field ${hook.name} ui.Hook`);
  lines.push("ui.Hook = {}", "");
  return lines;
}

export function moduleFilePath(moduleId: string): string {
  return `stubs/${moduleId}.lua`;
}

/** Render one module. Returns undefined when the page declares nothing. */
export function emitModule(mod: ModuleDef): EmittedFile | undefined {
  const hasContent =
    mod.classes.some((c) => c.fields.length || c.methods.length || c.index || c.parent) ||
    mod.freeFunctions.length ||
    mod.enums.length ||
    mod.events.length ||
    mod.hooks.length;
  if (!hasContent) return undefined;

  const lines = header(mod.title, mod.url);
  if (mod.events.length > 0) lines.push(see(mod.url, "overview"), "---@class Event", "Event = {}", "");
  for (const e of mod.enums) lines.push(...enumBlock(e, mod.url));
  for (const cls of mod.classes) lines.push(...classBlock(cls, mod.url));
  for (const fn of mod.freeFunctions) lines.push(...functionBlock(fn, "", mod.url));
  for (const ev of mod.events) lines.push(...eventBlock(ev, mod.url));
  lines.push(...hookBlocks(mod.hooks, mod.url));
  return { path: moduleFilePath(mod.id), content: lines.join("\n").replace(/\n+$/, "") + "\n" };
}

export function emitNamespaces(namespaces: string[], baseUrl: string): EmittedFile {
  const lines = header("namespace tables", baseUrl);
  for (const ns of namespaces) lines.push(`---@class ${ns}`, `${ns} = {}`, "");
  return { path: "stubs/_namespaces.lua", content: lines.join("\n").replace(/\n+$/, "") + "\n" };
}

export function emitGlobals(globals: GlobalTables, baseUrl: string): EmittedFile {
  const lines = header("config, id and var lookup tables", baseUrl);
  const configNames = Object.keys(globals.config).sort();
  lines.push(`---@see ${baseUrl}game/config/npctype.html#overview`, "---@class config");
  for (const name of configNames) lines.push(`---@field ${name} config.${name}`);
  lines.push("config = {}", "");
  for (const name of configNames) {
    const valueType = globals.config[name]!;
    lines.push(`---@class config.${name}`, `---@field [string] ${valueType}`, `config.${name} = {}`, "");
    lines.push("---@param id integer", `---@return ${valueType}`, `function config.${name}.FromID(id) end`, "");
  }
  lines.push(`---@see ${baseUrl}game/config/npctype.html#examples`, "---@class id");
  for (const name of globals.id) lines.push(`---@field ${name} id.${name}`);
  lines.push("id = {}", "");
  for (const name of globals.id) lines.push(`---@class id.${name}`, "---@field [string] integer", `id.${name} = {}`, "");
  lines.push(`---@see ${baseUrl}game/config/vartype.html#overview`, "---@class var");
  for (const name of globals.var) lines.push(`---@field ${name} var.${name}`);
  lines.push("var = {}", "");
  for (const name of globals.var) {
    lines.push(`---@class var.${name}`, "---@field [string] VarType", `var.${name} = {}`, "");
    lines.push("---@param id integer", "---@return VarType", `function var.${name}.FromID(id) end`, "");
  }
  return { path: "stubs/_globals.lua", content: lines.join("\n").replace(/\n+$/, "") + "\n" };
}

export function emitExtras(options: EmitOptions): EmittedFile {
  const lines = header("aliases and globally defined hook functions", options.baseUrl);
  for (const alias of options.aliases) {
    lines.push(`---@see ${options.baseUrl}${alias.see}`, `---@alias ${alias.name} ${alias.type}`, "");
  }
  for (const fn of options.globalFunctions) {
    lines.push(`---@see ${options.baseUrl}${fn.see}`, ...paramLines(fn.params), `function ${fn.name}(${paramNames(fn.params)}) end`, "");
  }
  return { path: "stubs/_extras.lua", content: lines.join("\n").replace(/\n+$/, "") + "\n" };
}

export function emitUnresolved(options: EmitOptions): EmittedFile {
  const lines = header("types referenced by the docs but not declared on any page", options.baseUrl);
  lines.push("-- Each name below is referenced in a signature or property table but has no page of its own.", "-- They are aliased to any so plugins type-check; see unresolved.md for where each is used.", "");
  for (const item of options.unresolved) {
    lines.push(`---@alias ${item.name} any`);
  }
  return { path: "stubs/_unresolved.lua", content: lines.join("\n").replace(/\n+$/, "") + "\n" };
}

/** Build the api_lookup index for a module. */
export function indexEntries(mod: ModuleDef, file: string): IndexEntry[] {
  const entries: IndexEntry[] = [];
  const url = (anchor: string) => `${mod.url}${anchor ? "#" + anchor : ""}`;
  for (const cls of mod.classes) {
    entries.push({ name: cls.name, kind: "class", module: mod.id, file, url: url(cls.anchor), signature: `---@class ${cls.name}${cls.parent ? " : " + cls.parent : ""}` });
    for (const f of cls.fields) entries.push({ name: `${cls.name}.${f.name}`, kind: "field", module: mod.id, file, url: url(f.anchor), signature: `${cls.name}.${f.name}: ${f.type}` });
    for (const m of cls.methods) entries.push({ name: `${cls.name}${m.sep}${m.name}`, kind: m.sep === ":" ? "method" : "function", module: mod.id, file, url: url(m.anchor), signature: signatureText(m) });
  }
  for (const fn of mod.freeFunctions) entries.push({ name: fn.name, kind: "function", module: mod.id, file, url: url(fn.anchor), signature: signatureText(fn) });
  for (const e of mod.enums) {
    entries.push({ name: e.name, kind: "enum", module: mod.id, file, url: url(e.anchor), signature: `---@enum ${e.name}` });
    for (const m of e.members) entries.push({ name: `${e.name}.${m.name}`, kind: "enum-member", module: mod.id, file, url: url(e.anchor), signature: m.value !== undefined ? `${e.name}.${m.name} = ${m.value}` : `${e.name}.${m.name}` });
  }
  for (const ev of mod.events) {
    const payload = ev.payload.length > 0 ? `fun(e: ${ev.name}Event)` : "fun()";
    entries.push({ name: `Event.${ev.name}`, kind: "event", module: mod.id, file, url: url(ev.anchor), signature: `Event.${ev.name}.Subscribe(ref: string, callback: ${payload}${ev.returnsBoolean ? ": boolean" : ""})` });
    for (const f of ev.payload) entries.push({ name: `${ev.name}Event.${f.name}`, kind: "field", module: mod.id, file, url: url(ev.anchor), signature: `${ev.name}Event.${f.name}: ${f.type}` });
  }
  for (const hook of mod.hooks) {
    entries.push({ name: `ui.Hook.${hook.name}`, kind: "hook", module: mod.id, file, url: url(hook.anchor), signature: hook.variants.map((v) => renderFunType(v, ["boolean?"])).join(" | ") });
  }
  return entries;
}
